# -*- coding: utf-8 -*-
"""
Модуль содержит абстрактный класс для сравнения самолётов.

Реализует принцип разделения интерфейсов (ISP):
только методы сравнения, без данных и сериализации.
"""

from abc import ABC, abstractmethod


class AeroplaneComparable(ABC):
    """
    Абстрактный базовый класс для сравнения самолётов.

    Определяет методы сравнения по скорости.
    Не включает данные или методы сериализации.

    Реализует принцип разделения интерфейсов (ISP):
    клиент, которому нужны только сравнения, не зависит от данных.
    """

    @abstractmethod
    def __lt__(self, other):
        """
        Сравнить по скорости (возрастание).

        Args:
            other: Другой объект для сравнения.

        Returns:
            True если скорость текущего меньше скорости другого.
        """
        pass

    @abstractmethod
    def __gt__(self, other):
        """
        Сравнить по скорости (убывание).

        Args:
            other: Другой объект для сравнения.

        Returns:
            True если скорость текущего больше скорости другого.
        """
        pass

    @abstractmethod
    def __le__(self, other):
        """
        Сравнить по скорости (<=).

        Args:
            other: Другой объект для сравнения.

        Returns:
            True если скорость текущего меньше или равна.
        """
        pass

    @abstractmethod
    def __ge__(self, other):
        """
        Сравнить по скорости (>=).

        Args:
            other: Другой объект для сравнения.

        Returns:
            True если скорость текущего больше или равна.
        """
        pass

    @abstractmethod
    def __eq__(self, other):
        """
        Сравнить два самолёта по позывному.

        Args:
            other: Другой объект для сравнения.

        Returns:
            True если позывные совпадают.
        """
        pass
